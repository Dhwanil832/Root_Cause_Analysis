"""V2 paper-inspired *one-step* gap/route coverage heuristic.

This is NOT V3 counterfactual planning: we do not generate hypothetical answers,
assign probabilities, or roll forward simulated evidence states. We optimize an
observable proxy: how many presently unresolved questions/alternative mechanisms
an admissible action could directly test or unlock, with burden penalties.
"""
from __future__ import annotations
from reasoning.specialist.components.frontier_policy import overlap
from reasoning.lead.components.planning_features import hypothesis_links, route_reachability, frontier_relevance


def _gap(gid, public):
    return next((x for x in public.get('gaps', []) if x.get('id') == gid), None)


def _relevance_of_action(action, gap):
    text = ' '.join(str(action.get(k, '')) for k in ('question','information_needed','possible_effect'))
    need = ' '.join(str(gap.get(k, '')) for k in ('question','expected_change'))
    return max(overlap(text, need), max((overlap(text, r.get('topic',''))
        for r in gap.get('routes_to_consider',[]) if isinstance(r,dict)),default=0.0))


def rank_one_step(runtime, actions, public, admissibility):
    """Deterministic cost-sensitive coverage ranking with explainable features.

    The candidate set is generated by the Lead LLM. Every candidate must pass
    the same host admissibility used by the baseline. All route knowledge comes
    from already public gap hints and known custodians, not hidden records.
    """
    results = []
    gaps = [g for g in public.get('gaps', []) if g.get('status') == 'open']
    if not gaps:
        gaps = [dict(g, id=gid) for gid, g in runtime.gaps.items() if g.get('status') == 'open']
    planning_view = {**public, 'gaps': gaps}
    for action in actions[:20]:
        if not isinstance(action, dict):
            continue
        base = admissibility(runtime, action, public)
        if base is None:
            continue
        gap = _gap(action['gap_id'], planning_view)
        if gap is None:
            continue
        route = action['route']
        matching = [g for g in route_reachability(route, planning_view) if g.get('status') == 'open']
        direct_link = _relevance_of_action(action, gap)
        # An action serving several gaps offers potential *coverage*; it does
        # not guarantee any custodian will return evidence or answer them.
        scope_gaps = [g for g in matching if
            _relevance_of_action(action, g) >= .12 or g['id'] == gap['id']]
        if not scope_gaps:
            scope_gaps = [gap]
        hypotheses = set().union(*(hypothesis_links(g, planning_view) for g in scope_gaps))
        mechanism_specific = sum(g.get('discrimination_class')=='mechanism_specific'
                                 for g in scope_gaps)
        graph_gaps = sum(frontier_relevance(g, planning_view) > .7 for g in scope_gaps)
        kind_score = {'causal':1.5,'operational':1.0,'access':.7}.get(gap.get('kind'),.7)
        # Route discovery can make existing proposed routes usable, but cannot
        # be credited with obtaining the documents themselves.
        unlock = (min(len(matching), 5) * 1.05 if action['mode']=='discover' else 0.0)
        scope_value = min(len(scope_gaps), 5) * .35
        discriminative_value = min(len(hypotheses), 5) * .46 + mechanism_specific * .40
        structural_value = min(graph_gaps,3) * .25
        is_request = 1 if action['mode']=='request' else 0
        declared_directness = max(0,min(3,int(action.get('directness',1))))
        burden = max(0, min(4, int(action.get('burden', 1))))
        cost = burden * .40 + (0.45 if action['mode']=='discover' else 0.0)
        attempted = sum(a.get('gap_id')==gap['id'] for a in runtime.attempts)
        redundancy = min(attempted, 4) * .35
        total = round(kind_score + scope_value + discriminative_value + structural_value +
                      unlock + is_request * .80 + direct_link * .60 + declared_directness * .60 - cost - redundancy, 3)
        results.append({'action':action,'score':total,'breakdown':{
            'policy':'v2_budgeted_question_coverage',
            'admissible_base':base,
            'direct_question_overlap':round(direct_link,3),
            'declared_directness':declared_directness,
            'question_scope_coverage':len(scope_gaps),
            'candidate_hypotheses_covered':len(hypotheses),
            'distinct_condition_questions':mechanism_specific,
            'unresolved_graph_frontier_needs':graph_gaps,
            'route_access':round(unlock,3),
            'open_needs_accessible_via_route':len(matching),
            'burden_and_repeat_cost':round(cost+redundancy,3),
            'score_type':'ordinal_heuristic_not_expected_information_gain',
            'method':'one_step_coverage_proxy',
        }})
    return sorted(results,key=lambda item:(-item['score'],item['action']['route'],item['action']['gap_id']))
